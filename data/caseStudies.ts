import { cases } from "./cases";

export const caseStudySections = [
  { id: "about", title: "О проекте" },
  { id: "task", title: "Задача" },
  { id: "problem", title: "Проблема" },
  { id: "solution", title: "Решение" },
  { id: "visual", title: "Визуальная система" },
  { id: "result", title: "Результат" },
] as const;

type CaseStudySectionId = typeof caseStudySections[number]["id"];

export type CaseStudy = {
  title: string;
  number: string;
  type: string;
  year: string;
  industry: string;
  mediaLayout?: "pages";
  sections: Record<CaseStudySectionId, string[]>;
  // Full website pages scroll; slides, social artwork and mockups fit in full.
  media: { kind: "website" | "image"; src: string; title: string; alt: string; width: number; height: number }[];
};

export function getCaseStudy(slug: string): CaseStudy | undefined {
  const index = cases.findIndex((item) => item.slug === slug);
  if (index === -1) return undefined;
  if (slug === "project-07") return abbyCaseStudy;
  if (slug === "project-03") return atlantaCaseStudy;
  if (slug === "project-09") return boondocksCaseStudy;
  if (slug === "project-10") return malepartusCaseStudy;
  const item = cases[index];
  return {
    title: item.title,
    number: String(index + 1).padStart(3, "0"),
    type: item.type,
    year: item.year,
    industry: item.industry,
    sections: {
      about: [item.description],
      task: ["Здесь появится задача проекта и запрос клиента."],
      problem: ["Здесь будет описана визуальная и бизнес-задача."],
      solution: ["Здесь появятся выбранное направление, логика и итоговое решение."],
      visual: ["Здесь будут описаны типографика, композиция, цвет и правила интерфейса."],
      result: ["Здесь появятся итог проекта и его ценность."],
    },
    media: [],
  };
}

